"""正式 spec 的索引生成与列表查询。"""

from __future__ import annotations

from typing import Any

from .errors import SpecifyError
from .io import atomic_write
from .paths import RepoPaths
from .validate.specs import SpecTreeValidator


class SpecIndex:
    """只从 formal specs 树生成确定性的类型和 spec ID 索引。"""

    def __init__(self, paths: RepoPaths, config: dict[str, Any]):
        """缓存项目路径和已配置的 spec 类型。"""

        self.paths = paths
        self.config = config

    def build(self) -> str:
        """扫描正式 spec，写入并返回稳定格式的索引 Markdown。"""

        validator = SpecTreeValidator(self.paths, self.config)
        issues = validator.validate()
        if issues:
            raise SpecifyError(issues[0].message, path=issues[0].path)

        groups: dict[str, list[str]] = {}
        for path in validator.files():
            spec_type = path.parent.parent.name
            groups.setdefault(spec_type, []).append(path.parent.name)

        lines = [
            "<!-- Generated by specify index build. Do not edit. -->",
            "",
            "# Spec Index",
            "",
        ]
        for spec_type in sorted(groups):
            lines.extend([f"## {spec_type[:1].upper()}{spec_type[1:]}", ""])
            for spec_id in sorted(groups[spec_type]):
                lines.append(f"- [`{spec_id}`](specs/{spec_type}/{spec_id}/spec.md)")
            lines.append("")
        result = "\n".join(lines).rstrip() + "\n"

        # 索引是派生文件，只能由本服务写入。
        atomic_write(self.paths.index, result)
        return result

    def list(self, spec_type: str | None = None) -> list[tuple[str, str]]:
        """返回按类型和 ID 排序的 formal spec 列表。"""

        items: list[tuple[str, str]] = []
        for path in SpecTreeValidator(self.paths, self.config).files():
            current_type = path.parent.parent.name
            if spec_type is None or current_type == spec_type:
                items.append((current_type, path.parent.name))
        return items


def build_index(paths: RepoPaths, config: dict[str, Any]) -> str:
    """提供 CLI 使用的索引重建入口。"""

    return SpecIndex(paths, config).build()


def list_specs(
    paths: RepoPaths, config: dict[str, Any], spec_type: str | None = None
) -> list[tuple[str, str]]:
    """提供 CLI 使用的 formal spec 列表入口。"""

    return SpecIndex(paths, config).list(spec_type)
