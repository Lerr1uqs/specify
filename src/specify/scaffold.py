def initialize(root: Path, config_path: Path | None) -> RepoPaths:
    """根据现有 init.yaml 或内置配置建立项目目录。"""

    source = config_path or root / "init.yaml"
    config = validate_config(load_yaml(source)) if source.exists() else DEFAULT_CONFIG
    paths = RepoPaths(root)
    paths.specs.mkdir(parents=True, exist_ok=True)
    _install_default_templates(paths)
    for status in ("proposed", "implemented", "rejected", "archived"):
        (paths.changes / status).mkdir(parents=True, exist_ok=True)
    dump_yaml(paths.config, config)

    # 初始化只创建空索引；索引内容始终由 index build 生成。
    if not paths.index.exists():
        atomic_write(
            paths.index,
            "<!-- Generated by specify index build. Do not edit. -->\n\n# Spec Index\n",
        )
    return paths


def create_spec(
    paths: RepoPaths,
    config: dict[str, Any],
    spec_type: str,
    spec_id: str,
    description: str | None = None,
) -> Path:
    """创建带显式 ID 占位符的正式 spec 骨架和可选简介。"""

    require(spec_type in config["specTypes"], f"未知 spec type：{spec_type}")
    require(validate_id(spec_id), f"spec id 必须为 kebab-case：{spec_id}")
    target = paths.specs / spec_type / spec_id / "spec.md"
    if target.exists():
        raise SpecifyError(f"spec 已存在：{spec_type}:{spec_id}")
    if description is not None:
        description = SpecMetadata.normalize_description(description)
    template_reference = config["specTypes"][spec_type].get("template")
    if template_reference:
        template_path = paths.spec / template_reference
        if not template_path.is_file():
            raise SpecifyError(
                f"spec type {spec_type} 的模板不存在：{template_path.as_posix()}"
            )
        template = template_path.read_text(encoding="utf-8")
    else:
        template = (
            "# contract\n\n## [contract-id] Contract title\n\n"
            "<!-- 填写该 Contract 的完整行为约定。 -->\n"
        )
    atomic_write(target, template)
    if description is not None:
        SpecMetadata(target).write_description(description)
    return target


def _install_default_templates(paths: RepoPaths) -> None:
    """将内置模板放入 spec/template，且保留项目已有模板。"""

    source = Path(__file__).parent / "assets" / "templates"
    paths.templates.mkdir(parents=True, exist_ok=True)
    for template in sorted(source.glob("*.md")):
        destination = paths.templates / template.name
        if not destination.exists():
            atomic_write(destination, template.read_text(encoding="utf-8"))


def parse_affect(value: str) -> tuple[str, str, str]:
    """解析 change create 使用的 spec 级影响目标。"""

    parts = value.split(":")
    if len(parts) != 3 or parts[2] not in {"create", "modify", "remove"}:
        raise SpecifyError(
            "--affect 格式必须为 <type>:<spec-id>:<create|modify|remove>"
        )
    if not validate_id(parts[1]):
        raise SpecifyError(f"无效的 spec id：{parts[1]}")
    return parts[0], parts[1], parts[2]


def create_change(
    paths: RepoPaths,
    config: dict[str, Any],
    kind: str,
    change_id: str,
    affects: tuple[str, ...],
) -> Path:
    """生成单一 change.md、tasks、YAML 元数据和 delta 编辑骨架。"""

    require(kind in config["kinds"], f"未知 change kind：{kind}")
    require(validate_id(change_id), f"change id 必须为 kebab-case：{change_id}")
    if any(change.id == change_id for change in scan_changes(paths)):
        raise SpecifyError(f"change id 已存在：{change_id}")

    parsed = [parse_affect(item) for item in affects]
    require(
        all(spec_type in config["specTypes"] for spec_type, _, _ in parsed),
        "affects 中有未配置的 spec type",
    )
    references = [f"{spec_type}:{spec_id}" for spec_type, spec_id, _ in parsed]
    require(len(set(references)) == len(parsed), "affects 中不能重复同一个 spec")

    target = paths.changes / "proposed" / kind / change_id
    target.mkdir(parents=True)
    now = datetime.now().astimezone().isoformat(timespec="seconds")
    metadata: dict[str, Any] = {
        "id": change_id,
        "title": change_id.replace("-", " ").title(),
        "kind": kind,
        "createdAt": now,
        "updatedAt": now,
    }
    if parsed:
        metadata["affects"] = [
            {"type": spec_type, "id": spec_id, "change": operation}
            for spec_type, spec_id, operation in parsed
        ]
    else:
        metadata["specImpact"] = {
            "kind": "none",
            "reason": "本次 change 不改变任何正式 Contract。",
        }
    dump_yaml(target / "meta-data.yaml", metadata)

    # change.md 按需填写，不预设 proposal/design 的固定章节。
    atomic_write(
        target / "change.md",
        "说明本次 change 的问题、背景和预期结果。简单修复可只保留一句话。\n",
    )
    atomic_write(
        target / "tasks.md",
        "# tasks\n\n## 1. Implementation\n\n- [ ] 1.1 完成本次变更并复核结果。\n",
    )
    for spec_type, spec_id, operation in parsed:
        path = target / "deltas" / spec_type / f"{spec_id}.md"
        atomic_write(path, _delta_template(operation))
    return target


def _delta_template(operation: str) -> str:
    """按 affects 的操作类型生成需作者补全的 Markdown 提示。"""

    if operation == "create":
        return "# delta\n\n## [ADDED] [new-contract] New Contract\n\n填写完整 Contract 正文。\n"
    return "# delta\n\n<!-- 添加对应的 [MODIFIED]、[REMOVED] 或 [RENAMED] 操作。 -->\n"
